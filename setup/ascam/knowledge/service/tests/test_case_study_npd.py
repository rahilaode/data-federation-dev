def actions_of(out, operation):
    return [a for a in out['actions'] if a['operation'] == operation]


def local(iri):
    return iri.rsplit('#', 1)[-1]


def test_artifacts_sync_and_lineage_binds_delimited_columns(npd):
    """ADR-0028: the NPD mapping writes rr:column "\"wlbNsMin\"" and templates {"wlbNpdidWellbore"};
    every term-map column must bind to its logical column, or the lineage is empty."""
    api, oid = npd
    version = api.get(f'/api/v1/obdf/{oid}/versions?limit=1').json()[0]
    detail = api.get(f"/api/v1/versions/{version['id']}").json()
    errors = [i for i in detail['issues'] if i['severity'] == 'error']
    assert errors == []
    assert not [i for i in detail['issues'] if i['code'] in ('logical_column_unresolved',
                                                               'logical_source_unresolved')]
    out = api.get(f'/api/v1/obdf/{oid}/lineage', params={
        'source': 'reporting', 'table': 'wellbore_coordinates', 'column': 'wlbNsMin'}).json()
    literal = [p for p in out['paths'] if p['role'] == 'literal_value']
    assert literal, out['paths']


# ── A001-A003: reporting (PostgreSQL) ─────────────────────────────────────────────
def test_a001_add_proposes_new_triples_map(npd):
    api, oid = npd
    out = impact(api, oid, operation='add', source='reporting', schema='public',
                 table='wellbore_mud', column='wlbMudPh', column_type='DECIMAL(6, 2)')
    assert out['decision'] == 'hitl' and out['pattern'] == 'P-001'
    assert actions_of(out, 'add_column')[0]['model'] == 'reporting'
    [new] = actions_of(out, 'add_triples_map')
    assert new['sql_query'] == ('SELECT "wellbore_mud_id", "wlbNpdidWellbore", "wlbMudPh" '
                                'FROM "reporting"."wellbore_mud" AS "wellbore_mud"')
    assert new['subject_template'].endswith('/wellbore/{"wlbNpdidWellbore"}/test/mud/{wellbore_mud_id}')
    [prop] = actions_of(out, 'add_datatype_property')
    assert prop['iri'] == NPDV + 'wlbMudPh' and prop['domain'] == [NPDV + 'WellboreDrillingMudSample']
    assert out['add_options']['range_iri'] == 'http://www.w3.org/2001/XMLSchema#decimal'


