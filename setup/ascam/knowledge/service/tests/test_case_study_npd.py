"""The NPD case study (ADR-0027): decisions and plans of ASCAM for the nine evaluation scenarios,
over the REAL artifacts in the repository.

The VDB, mapping, and ontology are read from setup/ (generated by setup/npd/tools). The Teiid
runtime metadata (SYS.*, SYSADMIN.Views, SYSADMIN.Usage) is built from that VDB in the same way
as for the social-assistance case study (test_case_study_view.py, ADR-0006): column-level usage
rows for the source of every view column, and object-level rows for every column a view refers
to. That Teiid accepts the VDB is checked on the running stack (setup/npd/README.md).

The events are those the orchestrator builds from the schema monitors, with the names in their
original case: NPD names are mixed case (ADR-0029).
"""
