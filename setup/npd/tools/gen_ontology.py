"""Writes the NPD ontology (RDF/XML) as Turtle, the format ASCAM reads and edits (ADR-0027).

The Executor appends its 𝒯 changes to the ontology as Turtle text blocks (owl:deprecated, new
data properties) and Knowledge parses 𝒯 as Turtle, so the RDF/XML file of the NPD Benchmark is
serialised once as Turtle. The graph is not changed: the script checks that both files hold the
same triples (blank nodes compared by graph isomorphism) before it writes anything.

Usage (from setup/npd):
    python3 tools/gen_ontology.py npd-benchmark/ontology/npd-v2-ql.owl ../vkg-system/config/ontology_file.ttl
"""
import sys

from rdflib import Graph
from rdflib.compare import isomorphic

PREFIXES = {
    'npdv': 'http://sws.ifi.uio.no/vocab/npd-v2#',
    'ptl': 'http://sws.ifi.uio.no/vocab/npd-v2-ptl#',
    'owl': 'http://www.w3.org/2002/07/owl#',
    'rdf': 'http://www.w3.org/1999/02/22-rdf-syntax-ns#',
    'rdfs': 'http://www.w3.org/2000/01/rdf-schema#',
    'xsd': 'http://www.w3.org/2001/XMLSchema#',
    'skos': 'http://www.w3.org/2004/02/skos/core#',
}


def main(source: str, target: str) -> None:
    original = Graph().parse(source, format='xml')
    for prefix, namespace in PREFIXES.items():
        original.bind(prefix, namespace, override=True, replace=True)
    body = original.serialize(format='turtle')
    header = ('# NPD ontology npd-v2-ql (ontop/npd-benchmark @ 5b1eeb3, ontology/npd-v2-ql.owl,\n'
              '# Apache-2.0) serialised as Turtle; the triples are unchanged.\n'
              '# Generated by setup/npd/tools/gen_ontology.py; do not edit by hand.\n')
    text = header + body
    again = Graph().parse(data=text, format='turtle')
    if len(again) != len(original) or not isomorphic(again, original):
        raise SystemExit('the Turtle serialisation does not hold the same graph')
    with open(target, 'w', encoding='utf-8') as fh:
        fh.write(text)
    print(f'{target}: {len(original)} triples, same graph as {source}')


if __name__ == '__main__':
    main(*sys.argv[1:3])
