"""Generates setup/data-source/{pgsql,mysql}/02-split-*.sql from the FK list of the full NPD dump.

npd-fkeys.txt: child|constraint|parent, from pg_constraint of the loaded dump (89 rows).
Run (from setup/npd): python3 tools/gen_split.py
"""
import os
from split import HERE, PG, MY
fks = []
for line in open(os.path.join(HERE, 'npd-fkeys.txt')):
    child, name, parent = [x.strip().strip('"') for x in line.split('|')]
    fks.append((child, name, parent))
cross = [f for f in fks if (f[0] in PG) != (f[2] in PG)]
assert len(fks) == 89 and len(cross) == 11, (len(fks), len(cross))
q = lambda n: '"%s"' % n
# PostgreSQL keeps PG: drop cross FKs whose child stays in PG, then drop the MySQL tables
pg_cross = [f for f in cross if f[0] in PG]
my_cross = [f for f in cross if f[0] in MY]
hdr = ('-- Generated by setup/npd/tools/gen_split.py from the 89 foreign keys of the NPD benchmark dump\n'
       '-- (ontop/npd-benchmark, data/postgres/npd.psql). Do not edit by hand.\n')
with open(os.path.join(HERE, '..', '..', 'data-source', 'pgsql', '02-split-reporting.sql'), 'w') as f:
    f.write(hdr + f'-- Source "reporting" keeps {len(PG)} tables (wells, stratigraphy, seismic surveys, production).\n'
            f'-- 1) {len(pg_cross)} foreign keys point to tables that move to "registry" (MySQL); a\n'
            '--    constraint cannot span two DBMSs, so they are removed here.\n'
            f'-- 2) The {len(MY)} tables of "registry" are dropped (RESTRICT: fails if anything else depends on them).\n'
            'BEGIN;\n')
    for c, n, p in sorted(pg_cross):
        f.write(f'ALTER TABLE {q(c)} DROP CONSTRAINT {q(n)};  -- -> {p}\n')
    f.write('DROP TABLE\n  ' + ',\n  '.join(q(t) for t in sorted(MY)) + '\n  RESTRICT;\nCOMMIT;\nANALYZE;\n')
# MySQL keeps MY (backticks: the entrypoint runs this file in the default sql_mode, without ANSI_QUOTES)
q = lambda n: '`%s`' % n
with open(os.path.join(HERE, '..', '..', 'data-source', 'mysql', '02-split-registry.sql'), 'w') as f:
    f.write(hdr + f'-- Source "registry" keeps {len(MY)} tables (licences, Petroleum Register, companies, fields,\n'
            '-- discoveries, facilities, TUF, business arrangement areas, reserves, investments).\n'
            f'-- 1) {len(my_cross)} foreign keys point to tables that move to "reporting" (PostgreSQL); removed.\n'
            f'-- 2) The {len(PG)} tables of "reporting" are dropped. FOREIGN_KEY_CHECKS is off only for the\n'
            '--    DROP, because these tables reference each other; step 1 already removed every\n'
            '--    constraint from a remaining table to a dropped one (checked by 04-check-registry.sh).\n')
    for c, n, p in sorted(my_cross):
        f.write(f'ALTER TABLE {q(c)} DROP FOREIGN KEY {q(n)};  -- -> {p}\n')
    f.write('SET FOREIGN_KEY_CHECKS = 0;\nDROP TABLE\n  ' + ',\n  '.join(q(t) for t in sorted(PG)) +
            ';\nSET FOREIGN_KEY_CHECKS = 1;\nANALYZE TABLE\n  ' + ',\n  '.join(q(t) for t in sorted(MY)) + ';\n')
print('pg_cross', len(pg_cross), 'my_cross', len(my_cross))
